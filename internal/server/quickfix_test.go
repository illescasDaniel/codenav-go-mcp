// Regression tests for block 9 of the QA fix plan (quick_fix: QF-001..QF-005), one group per bug.

// BUG-QF-003: line, code, choice and strict have no effect on organize_imports or fix_all, so they are refused
// (naming the flags passed) and nothing is written.
func TestQuickFixDiagnosticFlagsRefusedWithWholeFileFixes(t *testing.T) {
	cs, root := session(t, nil)
	src := "package qf3\n\nimport \"os\"\n\nfunc X() int { return 1 }\n"
	writeFile(t, root, "qf3/a.go", src)
	cases := []struct {
		args map[string]any
		want string
	}{
		{map[string]any{"organize_imports": true, "line": 3}, "line applies to diagnostic fixes, not to organize_imports"},
		{map[string]any{"organize_imports": true, "code": "UnusedVar", "apply": false}, "code applies to diagnostic fixes, not to organize_imports"},
		{map[string]any{"fix_all": true, "choice": "Remove"}, "choice applies to diagnostic fixes, not to fix_all"},
		{map[string]any{"fix_all": true, "strict": false}, "strict applies to diagnostic fixes, not to fix_all"},
	}
	for _, c := range cases {
		args := map[string]any{"file_path": "qf3/a.go"}
		for k, v := range c.args {
			args[k] = v
		}
		out, isErr := callIsError(t, cs, "quick_fix", args)
		if !isErr || !strings.Contains(out, c.want) {
			t.Errorf("%v: want a refusal with %q (isError=%v):\n%s", c.args, c.want, isErr, out)
		}
	}
	if got := readFile(t, root, "qf3/a.go"); got != src {
		t.Errorf("refused calls must not write:\n%s", got)
	}
	out, isErr := callIsError(t, cs, "quick_fix", map[string]any{"file_path": "qf3/a.go", "organize_imports": true})
	if isErr || !strings.Contains(out, "Organize Imports") {
		t.Errorf("organize_imports alone still applies (isError=%v):\n%s", isErr, out)
	}
}

// BUG-QF-005: a generated file is refused before its fixes are listed, so no choice is suggested and no
// listing is shown; the refusal is an error.
func TestQuickFixGeneratedFileRefusedBeforeListing(t *testing.T) {
	cs, root := session(t, nil)
	src := "// Code generated by tool; DO NOT EDIT.\n\npackage qf5\n\nfunc X() int { x := 1; return 1 }\n"
	writeFile(t, root, "qf5/gen.go", src)
	for _, args := range []map[string]any{
		{"file_path": "qf5/gen.go", "apply": false},
		{"file_path": "qf5/gen.go", "choice": "Remove"},
	} {
		out, isErr := callIsError(t, cs, "quick_fix", args)
		if !isErr || !strings.Contains(out, "gen.go is generated") {
			t.Errorf("%v: want the generated refusal (isError=%v):\n%s", args, isErr, out)
		}
		if strings.Contains(out, "Several fixes apply") || strings.Contains(out, "choice=") {
			t.Errorf("%v: no listing or choice hint for a generated file:\n%s", args, out)
		}
	}
	if got := readFile(t, root, "qf5/gen.go"); got != src {
		t.Errorf("the generated file must not change:\n%s", got)
	}
}

// BUG-QF-001: two workspace packages named lib export a different Foo. gopls offers one of them; both are listed,
// nothing is written by default, and choice= picks one.
func TestQuickFixAmbiguousImportListsEveryPackage(t *testing.T) {
	cs, root := session(t, nil)
	writeFile(t, root, "q006b/a/lib/lib.go", "package lib\n\nfunc Foo() int { return 1 }\n")
	writeFile(t, root, "q006b/b/lib/lib.go", "package lib\n\nfunc Foo() int { return 2 }\n")
	src := "package use\n\nfunc U() int { return lib.Foo() }\n"
	writeFile(t, root, "q006b/use/use.go", src)
	out, isErr := callIsError(t, cs, "quick_fix", map[string]any{"file_path": "q006b/use/use.go"})
	mustHave(t, "ambiguous", out, "Several fixes apply; nothing was changed", `Add import "example.com/fx/q006b/a/lib"`, `Add import "example.com/fx/q006b/b/lib"`)
	if !isErr {
		t.Errorf("an ambiguous import is refused (isError), not written:\n%s", out)
	}
	if got := readFile(t, root, "q006b/use/use.go"); got != src {
		t.Errorf("nothing may be written by default:\n%s", got)
	}
	out, isErr = callIsError(t, cs, "quick_fix", map[string]any{"file_path": "q006b/use/use.go", "choice": "b/lib", "apply": false})
	mustHave(t, "choice preview", out, `"example.com/fx/q006b/b/lib"`)
	if isErr || strings.Contains(out, "a/lib") {
		t.Errorf("choice=b/lib offers only b (isError=%v):\n%s", isErr, out)
	}
	out, isErr = callIsError(t, cs, "quick_fix", map[string]any{"file_path": "q006b/use/use.go", "choice": "b/lib"})
	if isErr {
		t.Fatalf("choice=b/lib must apply:\n%s", out)
	}
	got := readFile(t, root, "q006b/use/use.go")
	if !strings.Contains(got, `"example.com/fx/q006b/b/lib"`) || strings.Contains(got, "a/lib") {
		t.Errorf("choice=b/lib must add b and only b:\n%s", got)
	}
}

// BUG-QF-004: fix_all asks gopls with the file's diagnostics, so its fix-all edits (here "Remove empty value"
// and "Remove 'len(x)'") are found and written, and the file stays gofmt-clean.
func TestQuickFixFixAllAppliesGoplsEdits(t *testing.T) {
	cs, root := session(t, nil)
	src := "package qf4\n\nfunc Count(x []int) int {\n\tt := 0\n\tfor _ = range x {\n\t\tt++\n\t}\n\treturn t + len(x[0:len(x)])\n}\n"
	writeFile(t, root, "qf4/a.go", src)
	out, isErr := callIsError(t, cs, "quick_fix", map[string]any{"file_path": "qf4/a.go", "fix_all": true})
	if isErr || strings.Contains(out, "nothing to change") {
		t.Fatalf("fix_all must find gopls' edits (isError=%v):\n%s", isErr, out)
	}
	got := readFile(t, root, "qf4/a.go")
	if strings.Contains(got, "_ = range") || strings.Contains(got, "x[0:len(x)]") {
		t.Errorf("both fix-all edits must be written:\n%s", got)
	}
	if b, err := format.Source([]byte(got)); err != nil || string(b) != got {
		t.Errorf("the file must stay gofmt-clean (err=%v):\n%s", err, got)
	}
}
