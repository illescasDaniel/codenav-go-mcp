func copyTree(t *testing.T, from, to string) {
	t.Helper()
	err := filepath.WalkDir(from, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(from, p)
		if d.IsDir() {
			return os.MkdirAll(filepath.Join(to, rel), 0o755)
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(to, rel), b, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

// session runs the real server over an in-memory transport against a copy of the fixture.
func session(t *testing.T, env map[string]string) (*mcp.ClientSession, string) {
	t.Helper()
	if _, err := exec.LookPath("gopls"); err != nil {
		t.Skip("gopls not installed")
	}
	root := t.TempDir()
	copyTree(t, "../../testdata/fixture", root)
	t.Setenv(EnvWorkspace, root)
	t.Setenv(EnvReadOnly, "")
	for k, v := range env {
		t.Setenv(k, v)
	}
	srv, mgr := New("test")
	t.Cleanup(mgr.Close)
	ct, st := mcp.NewInMemoryTransports()
	ctx, cancel := context.WithTimeout(context.Background(), 120*time.Second)
	t.Cleanup(cancel)
	if _, err := srv.Connect(ctx, st, nil); err != nil {
		t.Fatal(err)
	}
	cs, err := mcp.NewClient(&mcp.Implementation{Name: "test"}, nil).Connect(ctx, ct, nil)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = cs.Close() })
	return cs, root
}

func call(t *testing.T, cs *mcp.ClientSession, name string, args map[string]any) string {
	t.Helper()
	res, err := cs.CallTool(context.Background(), &mcp.CallToolParams{Name: name, Arguments: args})
	if err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	for _, c := range res.Content {
		if tc, ok := c.(*mcp.TextContent); ok {
			b.WriteString(tc.Text)
		}
	}
	return b.String()
}

func readFile(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, rel))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

const scaleSig = "func Scale(s Shape, k float64, unused int)"

func TestWriteBlockedThenForcedThenUndone(t *testing.T) {
	cs, root := session(t, nil)
	broken := map[string]any{"file_path": "shapes/shapes.go", "old_string": scaleSig, "new_string": "func Scale(s Shape, k float64)"}

	out := call(t, cs, "edit", broken)
	if !strings.Contains(out, "Not written") || !strings.Contains(out, "app/app.go") {
		t.Fatalf("an edit breaking an importer must be blocked and name it:\n%s", out)
	}
	if !strings.Contains(readFile(t, root, "shapes/shapes.go"), scaleSig) {
		t.Fatal("a blocked edit must not touch the file")
	}

	id := out[strings.Index(out, `apply_edit(id="`)+len(`apply_edit(id="`):]
	id = id[:strings.Index(id, `"`)]
	if out := call(t, cs, "apply_edit", map[string]any{"id": id}); !strings.Contains(out, "Applied") {
		t.Fatalf("apply_edit:\n%s", out)
	}
	if strings.Contains(readFile(t, root, "shapes/shapes.go"), scaleSig) {
		t.Fatal("apply_edit did not write")
	}
	if out := call(t, cs, "undo_edit", nil); !strings.Contains(out, "Reverted") {
		t.Fatalf("undo_edit:\n%s", out)
	}
	if !strings.Contains(readFile(t, root, "shapes/shapes.go"), scaleSig) {
		t.Fatal("undo_edit did not restore")
	}
}

func TestWriteRefusals(t *testing.T) {
	cs, root := session(t, nil)
	_ = os.MkdirAll(filepath.Join(root, "vendor/x"), 0o755)
	gen := "// Code generated by x. DO NOT EDIT.\n\npackage shapes\n"
	_ = os.WriteFile(filepath.Join(root, "shapes/gen.go"), []byte(gen), 0o644)
	cases := map[string]map[string]any{
		"vendor":    {"file_path": "vendor/x/y.go", "new_text": "package x\n"},
		"not a .go": {"file_path": "shapes/notes.txt", "new_text": "x"},
		"generated": {"file_path": "shapes/gen.go", "old_string": "package shapes", "new_string": "package shapes\n\nvar X int"},
		"syntax":    {"file_path": "shapes/shapes.go", "old_string": "type Square", "new_string": "type ((("},
	}
	for name, args := range cases {
		out := call(t, cs, "edit", args)
		if strings.Contains(out, "Applied") {
			t.Errorf("%s: must be refused, got:\n%s", name, out)
		}
	}
	if _, err := os.Stat(filepath.Join(root, "vendor/x/y.go")); err == nil {
		t.Error("vendor file was written")
	}
}

