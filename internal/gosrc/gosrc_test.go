package gosrc

import "testing"

// EDIT-006: only a marker before the package clause makes a file generated (the go/ast rule).
func TestIsGenerated(t *testing.T) {
	cases := []struct {
		name, src string
		want      bool
	}{
		{"marker first", "// Code generated by x. DO NOT EDIT.\n\npackage p\n", true},
		{"licence, then marker, then package", "// Copyright 2024 X.\n\n// Code generated by x. DO NOT EDIT.\n\npackage p\n", true},
		{"marker after the package clause", "package p\n\n// Code generated by x. DO NOT EDIT.\n\nfunc After() int { return 1 }\n", false},
		{"marker inside a raw string", "package p\n\nvar raw = `line one\n// Code generated by x. DO NOT EDIT.\nline three`\n", false},
		{"marker inside a one-line string", "package p\n\nvar s = \"// Code generated by x. DO NOT EDIT.\"\n", false},
		{"no marker", "package p\n\nfunc F() {}\n", false},
	}
	for _, c := range cases {
		if got := IsGenerated(c.src); got != c.want {
			t.Errorf("%s: IsGenerated = %v, want %v", c.name, got, c.want)
		}
	}
}
